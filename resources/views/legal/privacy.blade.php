<h2>Overseas processing</h2>
<p>Some of those providers store or process information outside Australia, including in the United States. Where the Australian Privacy Principles apply, we take reasonable steps so that overseas recipients handle the information appropriately. Their own privacy rules may still differ from the Privacy Act.</p>

<h2>Cookies</h2>
<p>The site uses cookies and similar technologies for security, to remember a session, to measure visits (Google Analytics), and for advertising measurement (Google Ads and the Facebook pixel). Hotjar runs only on the immigration law page and may record what you do there, including text typed into the enquiry form. You can block or delete cookies in your browser. Blocking them can stop a form’s security check from completing.</p>

<h2>How long we keep it</h2>
<p>We keep enquiry, appointment, and payment records for as long as we need them to respond to you, provide legal services, and meet professional and legal record-keeping duties. When we no longer need the information, we delete it or remove details that identify you.</p>

